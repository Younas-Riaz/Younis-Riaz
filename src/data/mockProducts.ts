import { Product, SmartScoreBreakdown } from '../types';

export function calculateSmartScore(
  lowestPrice: number,
  averageRating: number,
  totalReviews: number,
  highestDiscount: number,
  freeShippingCount: number,
  totalPlatforms: number,
  inStock: boolean,
  categoryBenchmarkPrice: number
): SmartScoreBreakdown {
  // 1. Price Competitiveness (Max 35 points)
  // Cheaper relative to benchmark category price gives higher score
  const priceRatio = lowestPrice / (categoryBenchmarkPrice || 1000);
  let priceScore = 0;
  if (priceRatio <= 0.6) priceScore = 35;
  else if (priceRatio <= 0.8) priceScore = 32;
  else if (priceRatio <= 1.0) priceScore = 28;
  else if (priceRatio <= 1.2) priceScore = 23;
  else if (priceRatio <= 1.5) priceScore = 18;
  else priceScore = 12;

  // 2. Rating Score (Max 25 points) - 5 stars = 25, 4 stars = 20, etc.
  const ratingScore = Math.min(25, Math.max(0, Math.round((averageRating / 5) * 25)));

  // 3. Review Volume Confidence (Max 15 points) - more reviews = more reliable
  let reviewVolumeScore = 5;
  if (totalReviews > 2000) reviewVolumeScore = 15;
  else if (totalReviews > 1000) reviewVolumeScore = 13;
  else if (totalReviews > 500) reviewVolumeScore = 11;
  else if (totalReviews > 150) reviewVolumeScore = 9;

  // 4. Discount Score (Max 10 points)
  let discountScore = Math.min(10, Math.max(0, Math.round((highestDiscount / 40) * 10)));

  // 5. Shipping Score (Max 10 points) - free shipping availability across platforms
  const shippingRatio = totalPlatforms > 0 ? freeShippingCount / totalPlatforms : 0.5;
  const shippingScore = Math.round(shippingRatio * 10);

  // 6. Availability Score (Max 5 points)
  const availabilityScore = inStock ? 5 : 1;

  const totalScore = Math.min(99, Math.max(45, priceScore + ratingScore + reviewVolumeScore + discountScore + shippingScore + availabilityScore));

  // Determine pros & cons & recommendation text
  const pros: string[] = [];
  const cons: string[] = [];

  if (averageRating >= 4.6) pros.push(`Exceptional customer rating of ${averageRating.toFixed(1)}/5 stars`);
  if (totalReviews > 1000) pros.push(`High user verification with ${totalReviews.toLocaleString()} verified customer reviews`);
  if (highestDiscount >= 15) pros.push(`Competitive ${highestDiscount}% discount active across major retailers`);
  if (freeShippingCount > 0) pros.push('Fast & Free shipping offered by multiple partner merchants');
  if (lowestPrice < categoryBenchmarkPrice) pros.push('Priced well below category average benchmark');

  if (lowestPrice > categoryBenchmarkPrice * 1.2) cons.push('Higher price bracket compared to entry alternatives');
  if (highestDiscount < 5) cons.push('Modest promotional discounts currently available');
  if (freeShippingCount === 0) cons.push('Additional shipping fees apply on some platforms');

  if (pros.length === 0) pros.push('Reliable hardware build and modern features');
  if (cons.length === 0) cons.push('High market demand may affect short-term inventory');

  let recommendationReason = '';
  if (totalScore >= 90) {
    recommendationReason = `Highly Recommended: Stands out with an outstanding ${averageRating.toFixed(1)}/5 rating, deep retailer discounts up to ${highestDiscount}%, and superior price-to-performance ratio across multiple platforms.`;
  } else if (totalScore >= 80) {
    recommendationReason = `Strong Value Choice: Offers consistent market pricing with solid customer feedback (${averageRating.toFixed(1)}/5) and verified free delivery options.`;
  } else {
    recommendationReason = `Decent Option: Viable contender for specific feature needs, though competitive alternatives may offer larger discounts or lower base price.`;
  }

  return {
    priceScore,
    ratingScore,
    reviewVolumeScore,
    discountScore,
    shippingScore,
    availabilityScore,
    totalScore,
    recommendationReason,
    pros,
    cons,
  };
}

